import fs from 'node:fs';
import {randomBytes,randomUUID,createCipheriv,publicEncrypt,constants} from 'node:crypto';
import {createClient} from '@supabase/supabase-js';
if(process.env.VERCEL_ENV!=='preview'||process.env.VERCEL_PROJECT_ID!=='prj_VN5AuDmkx5m2VRsEH7VADIfUtJI1')throw Error('Only LDA preview may create the temporary QA learner');
const url=process.env.NEXT_PUBLIC_SUPABASE_URL?.trim(),key=process.env.SUPABASE_SERVICE_ROLE_KEY?.trim();
if(url!=='https://vznbhgatsozzendikvvf.supabase.co'||!key)throw Error('Wrong project');
const admin=createClient(url,key,{auth:{persistSession:false,autoRefreshToken:false}});
const email='lda-hazard-qa-'+randomUUID()+'@example.invalid',password=randomBytes(32).toString('base64url');
const created=await admin.auth.admin.createUser({email,password,email_confirm:true,user_metadata:{full_name:'Temporary LDA hazard playback QA',role:'learner'},app_metadata:{lda_hazard_qa:true}});
if(created.error||!created.data.user)throw Error('Unable to create QA learner: '+JSON.stringify({status:created.error?.status,code:created.error?.code,message:created.error?.message}));
const id=created.data.user.id;
console.log('Temporary QA learner created: '+id);
const role=await admin.from('account_roles').upsert({user_id:id,role:'learner'},{onConflict:'user_id,role'});
if(role.error)throw Error('Unable to configure QA learner role');
const aes=randomBytes(32),iv=randomBytes(12),cipher=createCipheriv('aes-256-gcm',aes,iv);
const payload=Buffer.concat([cipher.update(JSON.stringify({id,email,password,created_at:new Date().toISOString(),purpose:'temporary-hazard-playback-qa'})),cipher.final()]);
const wrapped=publicEncrypt({key:fs.readFileSync('qa-public.pem'),padding:constants.RSA_PKCS1_OAEP_PADDING,oaepHash:'sha256'},aes);
fs.mkdirSync('public',{recursive:true});
fs.writeFileSync('public/encrypted-qa.json',JSON.stringify({key:wrapped.toString('base64'),iv:iv.toString('base64'),tag:cipher.getAuthTag().toString('base64'),payload:payload.toString('base64')}));
console.log('QA credentials encrypted for the local verifier; no email was sent.');

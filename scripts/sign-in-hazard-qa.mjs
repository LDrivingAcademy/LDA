import fs from 'node:fs';
import {privateDecrypt,createDecipheriv,constants} from 'node:crypto';
import {parseEnv} from 'node:util';
import {createServerClient} from '@supabase/ssr';
const base=process.argv[2];
const app=process.argv[3]||base;
if(!/^https:\/\/lda-[a-z0-9]+-ldrivingacademys-projects\.vercel\.app$/.test(base||''))throw Error('Expected LDA preview');
if(!/^https:\/\/lda-[a-z0-9]+-ldrivingacademys-projects\.vercel\.app$/.test(app||'')&&app!=='https://ldrivingacademy.co.uk')throw Error('Expected LDA app preview or verified live domain');
const encryptedResponse=await fetch(base+'/encrypted-qa.json');
if(!encryptedResponse.ok||!encryptedResponse.headers.get('content-type')?.includes('application/json'))throw Error('QA preparation is not ready');
const e=await encryptedResponse.json();
const aes=privateDecrypt({key:fs.readFileSync('.tmp/lda-hazard-upload-private-v1/key.pem'),padding:constants.RSA_PKCS1_OAEP_PADDING,oaepHash:'sha256'},Buffer.from(e.key,'base64'));
const decipher=createDecipheriv('aes-256-gcm',aes,Buffer.from(e.iv,'base64'));decipher.setAuthTag(Buffer.from(e.tag,'base64'));
const qa=JSON.parse(Buffer.concat([decipher.update(Buffer.from(e.payload,'base64')),decipher.final()]).toString());
if(!qa.email.endsWith('@example.invalid')||!qa.email.startsWith('lda-hazard-qa-'))throw Error('Not a temporary QA account');
const env=parseEnv(fs.readFileSync('.env.codex.supabase-check.local','utf8'));
let cookies=[];
const client=createServerClient('https://vznbhgatsozzendikvvf.supabase.co',env.SUPABASE_PUBLISHABLE_KEY,{cookies:{getAll:()=>cookies,setAll:values=>{cookies=values;}}});
const signed=await client.auth.signInWithPassword({email:qa.email,password:qa.password});
if(signed.error||signed.data.user?.id!==qa.id)throw Error('Temporary learner sign-in failed');
const domain=new URL(app).hostname;
const state={cookies:cookies.map(c=>({name:c.name,value:c.value,domain,path:c.options?.path||'/',expires:Math.floor(Date.now()/1000)+3600,httpOnly:false,secure:true,sameSite:'Lax'})),origins:[]};
fs.writeFileSync('.tmp/lda-hazard-upload-private-v1/browser-state.json',JSON.stringify(state));
fs.writeFileSync('.tmp/lda-hazard-upload-private-v1/qa-identity.json',JSON.stringify({id:qa.id,email:qa.email,created_at:qa.created_at,preview:app}));
console.log('Signed in temporary learner using normal Supabase authentication; browser state saved privately.');
